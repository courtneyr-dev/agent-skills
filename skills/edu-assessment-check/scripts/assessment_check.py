#!/usr/bin/env python3
"""assessment_check: check that objectives, tasks, rubric criteria and scoring rationale align, that the
evidence a task collects can support its objective, and that the task adds no construct-irrelevant barrier.

  python3 assessment_check.py check FILE

Prints JSON. Exit 0 when nothing is found, 1 for any error or fairness flag or invalid input, 2 usage.
Python 3.9+ standard library only. Reading grade uses the Flesch-Kincaid formula with a heuristic
syllable count, so treat it as a screen that a teacher confirms, not a measurement.
"""
from __future__ import annotations

import json
import re
import sys
from typing import Any, Dict, List, Optional

LEVELS = ["remember", "understand", "apply", "analyze", "evaluate", "create"]
EVIDENCE = {"recall", "explanation", "product", "process-trace", "performance", "passing-tests", "ai-output"}
OUTPUT_ONLY = {"passing-tests", "ai-output"}
READING_MARGIN = 2.0

# Prompt text is read alongside the author's labels; where they disagree, the text wins.
RECALL_TEXT = re.compile(r"\b(multiple[- ]choice|true[- /]or[- /]false|fill[- ]in[- ]the[- ]blanks?|matching|define|definitions?|"
                         r"list the|name the|which of the following|pick one|choose one|circle the|recall|memori[sz]e|"
                         r"vocabulary quiz|label the)\b", re.I)
PERFORM_TEXT = re.compile(r"\b(build|calculate|compute|create|design|write|model|analy[sz]e|compare|explain|justify|recommend|"
                          r"construct|solve|trace|predict|debug|modify|query|plan|draft|present|demonstrate|enter|type|"
                          r"prepare|evaluate|interpret|develop|change)\b", re.I)
AI_TEXT = re.compile(r"\b(chat ?bot'?s?|chatgpt|gpt-?\d*|copilot|gemini|ai[- ]generated|generated by (an )?ai|ai tool'?s?|"
                     r"ai assistant'?s?|large language model|llm)\b", re.I)
AUTOGRADER_TEXT = re.compile(r"\b(autograder|passes? (all |the )?(\w+ )?(unit )?tests|all (the )?tests pass)\b", re.I)
LEARNER_EXPLAINS = re.compile(r"\b(explain|trace|in your own words|justify|describe why|walk (us |me )?through|annotate)\b", re.I)
PAID_TEXT = re.compile(r"\b(microsoft (excel|office|word|powerpoint|access|365)|excel 365|office 365|microsoft 365|"
                       r"paid licen[cs]e|subscription|adobe|photoshop|illustrator|tableau|quickbooks|spss|stata|matlab)\b", re.I)
ONLINE_TEXT = re.compile(r"\b(online|on the web|search the (web|internet)|internet|website|web ?site|https?://|log ?in|"
                         r"sign in|google)\b", re.I)
OFFLINE_TEXT = re.compile(r"\b(printed|paper|offline|no computer|no internet|hand-?out|low[- ]bandwidth)\b", re.I)


def read_prompt(t: Dict[str, Any]) -> Dict[str, Any]:
    """What the prompt text itself asks for, independent of the declared labels."""
    text = " ".join([str(t.get("prompt", ""))] + [str(x) for x in t.get("tools", []) if isinstance(x, str)])
    found: Dict[str, Any] = {"level": None, "evidence": None, "paid": None, "online": None,
                             "offline_route": bool(OFFLINE_TEXT.search(text))}
    recall, perform = RECALL_TEXT.search(text), PERFORM_TEXT.search(text)
    if recall and not perform:
        found["level"], found["evidence"] = "remember", {"recall"}
        found["why"] = "reads as a recall quiz (%r)" % recall.group(0)
    explains = LEARNER_EXPLAINS.search(text)
    ai, grader = AI_TEXT.search(text), AUTOGRADER_TEXT.search(text)
    if (ai or grader) and not explains:
        found["evidence"] = ({"ai-output"} if ai else set()) | ({"passing-tests"} if grader else set())
        found["why"] = "collects %s with no learner explanation or trace" % (
            "AI-generated output (%r)" % ai.group(0) if ai else "an autograder result (%r)" % grader.group(0))
    paid, online = PAID_TEXT.search(text), ONLINE_TEXT.search(text)
    found["paid"] = paid.group(0) if paid else None
    found["online"] = online.group(0) if online else None
    return found


def syllables(word: str) -> int:
    w = re.sub(r"[^a-z]", "", word.lower())
    if not w:
        return 0
    groups = re.findall(r"[aeiouy]+", w)
    n = len(groups)
    if w.endswith("e") and not w.endswith(("le", "ee", "ye")) and n > 1:
        n -= 1
    return max(1, n)


def fk_grade(text: str) -> Optional[float]:
    sentences = [s for s in re.split(r"[.!?]+(?:\s|$)", text) if re.search(r"[A-Za-z]", s)]
    words = re.findall(r"[A-Za-z][A-Za-z'-]*", text)
    if len(words) < 12 or not sentences:
        return None
    syl = sum(syllables(w) for w in words)
    return round(0.39 * len(words) / len(sentences) + 11.8 * syl / len(words) - 15.59, 1)


def validate(doc: Any) -> List[str]:
    if not isinstance(doc, dict):
        return ["the file must be a JSON object"]
    errs = []
    for key in ("objectives", "tasks", "rubric"):
        if not isinstance(doc.get(key), list) or not doc[key]:
            errs.append("%s must be a non-empty list" % key)
    if errs:
        return errs
    for o in doc["objectives"]:
        if not isinstance(o, dict) or not o.get("id") or not o.get("text"):
            errs.append("every objective needs id and text")
        elif o.get("level") not in LEVELS:
            errs.append("objective %s level %r is not one of %s" % (o["id"], o.get("level"), ", ".join(LEVELS)))
    for t in doc["tasks"]:
        if not isinstance(t, dict) or not t.get("id") or not isinstance(t.get("objective_ids"), list):
            errs.append("every task needs id and an objective_ids list")
            continue
        if t.get("cognitive_level") not in LEVELS:
            errs.append("task %s cognitive_level %r is not one of %s" % (t["id"], t.get("cognitive_level"), ", ".join(LEVELS)))
        bad = [e for e in t.get("evidence", []) if e not in EVIDENCE]
        if not t.get("evidence") or bad:
            errs.append("task %s evidence must be a non-empty list from %s" % (t["id"], ", ".join(sorted(EVIDENCE))))
    for c in doc["rubric"]:
        if not isinstance(c, dict) or not c.get("id"):
            errs.append("every rubric criterion needs an id")
    ids = [x.get("id") for k in ("objectives", "tasks", "rubric") for x in doc[k] if isinstance(x, dict)]
    dup = sorted({i for i in ids if i and ids.count(i) > 1})
    if dup:
        errs.append("duplicate ids: %s" % ", ".join(dup))
    return errs


def check(doc: Dict[str, Any]) -> Dict[str, Any]:
    errors: List[Dict[str, str]] = []
    flags: List[Dict[str, str]] = []
    ctx = doc.get("context", {}) if isinstance(doc.get("context"), dict) else {}
    objectives = {o["id"]: o for o in doc["objectives"]}
    tasks = {t["id"]: t for t in doc["tasks"]}

    def err(code, where, msg):
        errors.append({"code": code, "where": where, "message": msg})

    def flag(code, where, msg):
        flags.append({"code": code, "where": where, "message": msg})

    read: Dict[str, Dict[str, Any]] = {}
    eff_level: Dict[str, str] = {}
    eff_evidence: Dict[str, set] = {}
    for t in tasks.values():
        for oid in t["objective_ids"]:
            if oid not in objectives:
                err("unknown-objective", t["id"], "task names objective %s, which is not defined" % oid)
        r = read[t["id"]] = read_prompt(t)
        eff_level[t["id"]] = t["cognitive_level"]
        eff_evidence[t["id"]] = set(t["evidence"])
        if r["level"] and LEVELS.index(r["level"]) < LEVELS.index(t["cognitive_level"]):
            eff_level[t["id"]] = r["level"]
        weak = OUTPUT_ONLY | {"recall"}
        if r["evidence"] is not None and set(t["evidence"]) - weak - r["evidence"]:
            eff_evidence[t["id"]] = r["evidence"] | (set(t["evidence"]) & weak)
        if eff_level[t["id"]] != t["cognitive_level"] or eff_evidence[t["id"]] != set(t["evidence"]):
            err("label-text-mismatch", t["id"], "labeled %s with %s evidence, but the prompt %s; judged as %s with %s evidence"
                % (t["cognitive_level"], ", ".join(sorted(t["evidence"])), r.get("why", "disagrees"),
                   eff_level[t["id"]], ", ".join(sorted(eff_evidence[t["id"]]))))
    crit_by_obj: Dict[str, List[str]] = {o: [] for o in objectives}
    for c in doc["rubric"]:
        tid, oid = c.get("task_id"), c.get("objective_id")
        if tid not in tasks or oid not in objectives:
            err("rubric-misaligned", c["id"], "criterion must name a defined task and objective (got %s, %s)" % (tid, oid))
            continue
        if oid not in tasks[tid]["objective_ids"]:
            err("rubric-misaligned", c["id"], "task %s does not assess objective %s" % (tid, oid))
        levels = c.get("levels", [])
        if not isinstance(levels, list) or len(levels) < 2 or not all(isinstance(l, dict) and l.get("descriptor") for l in levels):
            err("no-performance-levels", c["id"], "a criterion needs at least two described performance levels")
        if not str(c.get("scoring_rationale", "")).strip():
            err("no-scoring-rationale", c["id"], "say why each level reflects the objective, so scorers apply it the same way")
        crit_by_obj[oid].append(c["id"])

    summary = {}
    for oid, o in objectives.items():
        mine = [t for t in tasks.values() if oid in t["objective_ids"]]
        need = LEVELS.index(o["level"])
        summary[oid] = {"level": o["level"], "tasks": [t["id"] for t in mine], "criteria": crit_by_obj[oid]}
        if not mine:
            err("objective-unassessed", oid, "no task collects evidence for this objective")
            continue
        if not crit_by_obj[oid]:
            err("objective-unscored", oid, "no rubric criterion scores this objective")
        top = max(LEVELS.index(eff_level[t["id"]]) for t in mine)
        kinds = set().union(*(eff_evidence[t["id"]] for t in mine))
        if need >= LEVELS.index("apply") and (top < LEVELS.index("apply") or kinds <= {"recall"}):
            err("recall-only-evidence", oid, "objective asks learners to %s, but its tasks only collect %s-level recall; "
                "a recall quiz cannot evidence an application or performance objective" % (o["level"], LEVELS[top]))
        elif top < need:
            err("level-mismatch", oid, "objective level %s is above the highest task level %s" % (o["level"], LEVELS[top]))
        if need >= LEVELS.index("understand") and kinds <= OUTPUT_ONLY:
            err("output-only-evidence", oid, "passing tests or AI-generated output do not show the learner's understanding; "
                "add an explanation, a trace or an observed performance")

    target = ctx.get("reading_grade_target")
    for t in tasks.values():
        constructs = " ".join(str(objectives[o].get("construct", "")) for o in t["objective_ids"] if o in objectives).lower()
        d = t.get("demands", {}) if isinstance(t.get("demands"), dict) else {}
        grade = fk_grade(str(t.get("prompt", "")))
        if isinstance(target, (int, float)) and grade is not None and grade > target + READING_MARGIN \
                and "reading" not in constructs:
            shown = "about grade %.1f" % grade if grade <= 18 else "above grade 18 (Flesch-Kincaid %.1f)" % grade
            flag("irrelevant-reading-demand", t["id"], "prompt reads %s against a grade %s target; "
                 "simplify the wording without lowering the task's demand" % (shown, target))
        r = read[t["id"]]
        if d.get("paid_software") or r["paid"]:
            flag("paid-software", t["id"], "the task requires paid software%s; offer a free or school-provided route"
                 % (" (the prompt names %r)" % r["paid"] if r["paid"] else ""))
        described = (isinstance(d.get("offline_alternative"), str) and len(d["offline_alternative"].strip()) > 10) or r["offline_route"]
        if r["online"] and not described:
            flag("no-offline-route", t["id"], "the prompt requires an online step (%r) and names no offline or low-bandwidth "
                 "route; describe it in the prompt or in demands.offline_alternative" % r["online"])
        elif d.get("internet_required") and not d.get("offline_alternative"):
            flag("no-offline-route", t["id"], "the task needs internet access and names no offline or low-bandwidth alternative")
        if d.get("color_only_cues"):
            flag("color-only", t["id"], "meaning carried by color alone excludes some learners; add text or pattern cues")
        if d.get("timed_minutes") and not d.get("construct_is_speed"):
            flag("speed-not-in-construct", t["id"], "a time limit adds speed to a construct that does not include it")
        brand = d.get("brand_specific_tool")
        if brand and str(brand).lower() not in constructs:
            flag("tool-specific", t["id"], "requiring %s tests tool familiarity, not the stated construct" % brand)

    for w in doc.get("student_work", []) or []:
        if not (isinstance(w, dict) and w.get("synthetic") is True and "SYNTHETIC" in str(w.get("label", ""))):
            err("unlabeled-student-work", str(w.get("id", "?")) if isinstance(w, dict) else "?",
                "student work must be labeled synthetic; real student work goes through edu-student-data-guard first")

    return {"ok": not errors and not flags, "errors": errors, "flags": flags, "objectives": summary,
            "label": doc.get("label", "")}


def main(argv: Optional[List[str]] = None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    if len(argv) != 2 or argv[0] != "check":
        sys.stderr.write("usage: assessment_check.py check FILE\n")
        return 2
    try:
        with open(argv[1], encoding="utf-8") as fh:
            doc = json.load(fh)
    except (OSError, ValueError) as exc:
        print(json.dumps({"ok": False, "status": "invalid", "errors": [str(exc)]}, indent=2))
        return 1
    problems = validate(doc)
    if problems:
        print(json.dumps({"ok": False, "status": "invalid", "errors": problems}, indent=2))
        return 1
    result = check(doc)
    print(json.dumps(result, indent=2, ensure_ascii=False))
    return 0 if result["ok"] else 1


if __name__ == "__main__":
    sys.exit(main())

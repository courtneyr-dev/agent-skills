"""frig: command line for the factory rig adapters. All commands print one JSON document."""
from __future__ import annotations

import argparse
import json
import os
import shutil
import sys
from typing import Any, Dict, List

from . import drift as drift_mod
from . import gate, noodle_control, noodle_run, noodle_setup, orchestrate
from .canon import sha_file
from .contract import contract_hash, frontier, load_contracts, load_tasks

HERE = os.path.dirname(os.path.abspath(__file__))
SKILL_DIR = os.path.normpath(os.path.join(HERE, "..", ".."))
REGISTRY = os.path.join(SKILL_DIR, "registry", "components.json")
UPSTREAM_ROOT = os.environ.get("FRIG_UPSTREAM_ROOT") or os.path.join(SKILL_DIR, "upstream")
NOODLE_BIN = os.environ.get("FRIG_NOODLE_BIN") or "noodle"
NOODLE_TOML = """# Generated by `frig noodle-init` from the pinned Noodle schema (config/types_defaults.go).
mode = "supervised"

[routing.defaults]
provider = "codex"
model = "{model}"

[skills]
paths = [".agents/skills"]

[concurrency]
max_concurrency = 1

[runtime]
default = "process"

[runtime.process]
max_concurrent = 1

[agents.codex]
path = "{bin_dir}"

[agents.claude]
path = "{bin_dir}"

[adapters.backlog]
skill = "factory-execute"

[adapters.backlog.scripts]
sync = "{bin_dir}/frig-backlog sync"
done = "{bin_dir}/frig-backlog done"
add = "{bin_dir}/frig-backlog add"
edit = "{bin_dir}/frig-backlog edit"

[server]
enabled = false
"""


def out(obj: Any, code: int = 0) -> int:
    print(json.dumps(obj, indent=2, sort_keys=True))
    return code


def main(argv: List[str] = None) -> int:
    ap = argparse.ArgumentParser(prog="frig")
    sub = ap.add_subparsers(dest="cmd", required=True)

    def ws_arg(p):
        p.add_argument("--ws", required=True)

    p = sub.add_parser("frontier"); ws_arg(p); p.add_argument("--backend", default="noodle")
    p = sub.add_parser("dispatch"); ws_arg(p)
    p.add_argument("--task", required=True); p.add_argument("--backend", default="noodle")
    p.add_argument("--owner-pid", type=int, default=0, help="defaults to the pid in .factory-rig/noodle.pid"); p.add_argument("--noodle-bin")
    p.add_argument("--provider", default="codex"); p.add_argument("--model", default="")
    p = sub.add_parser("review"); ws_arg(p)
    p.add_argument("--attempt", required=True); p.add_argument("--verdict", required=True, choices=["approve", "reject"])
    p.add_argument("--reviewer-provider", required=True); p.add_argument("--reviewer-model", default="")
    p.add_argument("--implementer-provider", required=True); p.add_argument("--findings", default="")
    p.add_argument("--worktree")
    p = sub.add_parser("check"); ws_arg(p); p.add_argument("--attempt", required=True); p.add_argument("--worktree")
    p = sub.add_parser("complete"); ws_arg(p); p.add_argument("--attempt", required=True); p.add_argument("--worktree")
    p.add_argument("--no-close-noodle", action="store_true")
    p = sub.add_parser("abandon"); ws_arg(p); p.add_argument("--attempt", required=True); p.add_argument("--why", required=True)
    p = sub.add_parser("noodle-run"); ws_arg(p); p.add_argument("--noodle-bin", default=NOODLE_BIN, help="default $FRIG_NOODLE_BIN, else noodle on PATH")
    p.add_argument("--max-scheduler-sessions", type=int, default=3); p.add_argument("--max-wall", type=float, default=1800.0)
    p.add_argument("--exit-when-idle", action="store_true")
    p = sub.add_parser("reconcile"); ws_arg(p)
    p = sub.add_parser("report"); ws_arg(p)
    p = sub.add_parser("fence"); ws_arg(p); p.add_argument("--task", required=True)
    p.add_argument("--epoch", type=int, default=None, help="refuse unless the lease is at this epoch")
    p = sub.add_parser("noodle-init"); ws_arg(p); p.add_argument("--model", default="gpt-6-luna"); p.add_argument("--bin-dir", required=True)
    p = sub.add_parser("registry-verify"); p.add_argument("--registry", default=REGISTRY)
    p = sub.add_parser("render-overrides")
    p = sub.add_parser("drift"); p.add_argument("--registry", default=REGISTRY)
    p.add_argument("--upstream-root", default=UPSTREAM_ROOT, help="default $FRIG_UPSTREAM_ROOT, else <skill>/upstream")
    a = ap.parse_args(argv)

    if a.cmd == "registry-verify":
        errs = drift_mod.verify_registry(drift_mod.load(a.registry))
        return out({"ok": not errs, "errors": errs}, 0 if not errs else 1)
    if a.cmd == "render-overrides":
        reg = os.path.join(os.path.dirname(REGISTRY), "overrides.json")
        n = drift_mod.render_overrides(reg, os.path.join(os.path.dirname(os.path.dirname(REGISTRY)), "references", "overrides.md"))
        return out({"ok": True, "overrides": n})
    if a.cmd == "drift":
        res = drift_mod.drift(drift_mod.load(a.registry), a.upstream_root)
        bad = [r for r in res if r["state"] in ("drifted", "pin-unreachable", "missing-clone")]
        return out({"ok": not bad, "components": res}, 0 if not bad else 1)

    ws = orchestrate.Workspace(a.ws)
    if a.cmd == "frontier":
        el, rej = frontier(load_tasks(ws.project), load_contracts(ws.rig_dir), ws.specs_dir, a.backend)
        return out({"eligible": el, "rejected": rej})
    if a.cmd == "abandon":
        return out(orchestrate.abandon(ws, a.attempt, a.why))
    if a.cmd == "noodle-run":
        def active() -> int:
            n = 0
            for at in ws.attempts():
                if at.get("event") == "dispatched":
                    lease = ws.leases.status(load_contracts(ws.rig_dir)[at["task_id"]]["repo"], at["task_id"])
                    n += 1 if lease and lease["state"] == "active" and lease["attempt_id"] == at["attempt_id"] else 0
            return n
        r = noodle_run.run(a.noodle_bin, ws.repo, ws.rig_dir, ws.noodle_runtime, active, a.max_scheduler_sessions, a.max_wall, a.exit_when_idle)
        return out(r)
    if a.cmd == "dispatch":
        pid = a.owner_pid
        if not pid:
            try:
                pid = int(open(os.path.join(ws.rig_dir, "noodle.pid")).read().strip())
            except (OSError, ValueError):
                return out({"ok": False, "reasons": ["no --owner-pid and no readable .factory-rig/noodle.pid; start `frig noodle-run` first"]}, 3)
        r = orchestrate.dispatch(ws, a.task, a.backend, pid, a.noodle_bin, a.provider, a.model)
        return out(r, 0 if r["ok"] else 3)
    if a.cmd == "review":
        attempt = ws.attempt(a.attempt)
        wt = orchestrate.worktree_for(ws, attempt, a.worktree)
        cand = gate.git(wt, "rev-parse", "HEAD")
        findings = json.load(open(a.findings)) if a.findings else []
        path = gate.write_review(ws.rig_dir, {
            "task_id": attempt["task_id"], "attempt_id": a.attempt, "contract_hash": attempt["contract_hash"],
            "candidate_sha": cand, "base_sha": attempt["base_sha"], "verdict": a.verdict,
            "reviewer": {"provider": a.reviewer_provider, "model": a.reviewer_model},
            "implementer": {"provider": a.implementer_provider}, "findings": findings})
        return out({"ok": True, "review": path, "candidate_sha": cand})
    if a.cmd == "check":
        attempt = ws.attempt(a.attempt)
        ctx = orchestrate.context(ws, attempt, orchestrate.worktree_for(ws, attempt, a.worktree))
        r = gate.check(ctx, ws.leases)
        return out(r, 0 if r["ok"] else 4)
    if a.cmd == "complete":
        r = orchestrate.complete(ws, a.attempt, a.worktree, not a.no_close_noodle)
        return out(r, 0 if r["ok"] else 4)
    if a.cmd == "reconcile":
        r = orchestrate.reconcile(ws)
        return out(r, 0 if not r["unresolved"] else 5)
    if a.cmd == "fence":
        c = load_contracts(ws.rig_dir)[a.task]
        return out(ws.leases.fence(c["repo"], a.task, expected_epoch=a.epoch))
    if a.cmd == "noodle-init":
        path = os.path.join(ws.repo, ".noodle.toml")
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(NOODLE_TOML.format(model=a.model, bin_dir=os.path.abspath(os.path.expanduser(a.bin_dir))))
        return out({"ok": True, "wrote": [path] + noodle_setup.install(ws.repo)})
    if a.cmd == "report":
        tasks = load_tasks(ws.project)
        contracts = load_contracts(ws.rig_dir)
        rep: Dict[str, Any] = {"tasks": {}, "open_receipts": [r["key"] for r in ws.receipts.open_receipts()]}
        for tid, t in tasks.items():
            c = contracts.get(tid)
            lease = ws.leases.status(c["repo"], tid) if c else None
            rep["tasks"][tid] = {"status": t.get("status"), "lease": {k: lease[k] for k in ("state", "backend", "epoch", "attempt_id")} if lease else None}
        rep["attempts"] = ws.attempts()
        return out(rep)
    return 2


if __name__ == "__main__":
    sys.exit(main())
